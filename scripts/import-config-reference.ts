// One foundry.toml key, as Foundry's \`cargo config-reference\` writes it.
export type Setting = {
  key: string;
  section: string | null;
  type: string;
  table?: boolean;
  default?: string | null;
  values?: string[];
  aliases?: string[];
  env?: string[];
  deprecated?: string;
  description: string;
};
export type Snapshot = {
  schemaVersion: 1;
  source: { repository: "foundry-rs/foundry"; commit: string; path: typeof sourcePath };
  settings: Setting[];
};
export type Region = {
  file: string;
  /** Index of the first character after the begin marker. */
  start: number;
  /** Index of the end marker. */
  end: number;
  keys: string[];
  exclude: string[];
  level: number;
  fallback: boolean;
  title?: string;
  /** The nearest authored H2 and H3/H4 headings before the region, for default-config.mdx. */
  context: string;
};
export type Assignment = {
  regions: { region: Region; settings: Setting[] }[];
  fallback: Setting[];
  warnings: string[];
};

