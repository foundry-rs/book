const read = (root: string, path: string) => readFileSync(join(root, path), "utf8");
const git = (cwd: string, ...args: string[]) =>
  execFileSync("git", ["-C", cwd, ...args], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  }).trim();

export function validateSettings(value: unknown, origin: string): Setting[] {
  const fail = (reason: string): never => {
    throw new Error(`${origin}: ${reason}`);
  };
  const reference = value as { schemaVersion?: unknown; settings?: unknown };
  if (reference?.schemaVersion !== 1) fail("expected schemaVersion 1");
  if (!Array.isArray(reference.settings) || !reference.settings.length) fail("expected settings");
  const keys = new Set<string>();
  const strings = (item: unknown) =>
    item === undefined || (Array.isArray(item) && item.every((entry) => typeof entry === "string"));
  for (const setting of reference.settings as Setting[]) {
    const key = setting?.key;
    if (typeof key !== "string" || !/^[A-Za-z0-9_]+(\.[A-Za-z0-9_]+)*$/.test(key))
      fail(`invalid key ${JSON.stringify(key)}`);
    if (keys.has(key)) fail(`duplicate key ${key}`);
    keys.add(key);
    if (setting.section !== null && typeof setting.section !== "string")
      fail(`${key}: invalid section`);
    if (setting.section && key !== setting.section && !key.startsWith(`${setting.section}.`))
      fail(`${key}: key is outside its section ${setting.section}`);
    if (typeof setting.type !== "string" || !setting.type) fail(`${key}: missing type`);
    if (typeof setting.description !== "string") fail(`${key}: missing description`);
    if (setting.default != null && typeof setting.default !== "string")
      fail(`${key}: default must be a TOML string`);
    if (setting.deprecated !== undefined && typeof setting.deprecated !== "string")
      fail(`${key}: deprecated must be a string`);
    if (![setting.values, setting.aliases, setting.env].every(strings))
      fail(`${key}: values, aliases and env must be string arrays`);
  }
  return reference.settings as Setting[];
}

function parseAttributes(text: string, where: string) {
  const attributes: Record<string, string | true> = {};
  const rest = text.replace(/(\w+)(?:="([^"]*)"|=(\S+))?/g, (_, name: string, quoted, bare) => {
    if (name in attributes) throw new Error(`${where}: repeated attribute ${name}`);
    attributes[name] = quoted ?? bare ?? true;
    return "";
  });
  if (rest.trim()) throw new Error(`${where}: cannot parse ${JSON.stringify(rest.trim())}`);
  return attributes;
}

const headingContext = (before: string) => {
  // Generated content is ignored so the context doesn't depend on a previous import.
  before = before.replace(/\{\/\* config-reference:begin[\s\S]*?config-reference:end \*\/\}/g, "");
  let page = "";
  let group = "";
  let fence = false;
  for (const line of before.split("\n")) {
    if (/^ {0,3}(```|~~~)/.test(line)) fence = !fence;
    if (fence) continue;
    const heading = line.match(/^(#{2,4}) (.+)$/);
    if (!heading) continue;
    const text = heading[2].replace(/`/g, "").replace(/:$/, "").trim();
    if (heading[1] === "##") [page, group] = [text, ""];
    else group = text;
  }
  return group ? `${page} - ${group}` : page;
};

// Parse the generated regions of one page, rejecting malformed or nested markers.
export function parseRegions(text: string, file: string): Region[] {
  const regions: Region[] = [];
  let cursor = 0;
  for (const match of text.matchAll(beginPattern)) {
    const where = `${file}:${text.slice(0, match.index).split("\n").length}`;
    if (match.index < cursor) throw new Error(`${where}: nested config-reference region`);
    const start = match.index + match[0].length;
    const end = text.indexOf(endMarker, start);
    if (end < 0) throw new Error(`${where}: config-reference region has no end marker`);
    const nested = text.slice(start, end).search(beginPattern);
    if (nested >= 0) throw new Error(`${where}: nested config-reference region`);
    if (text.slice(cursor, match.index).includes(endMarker))
      throw new Error(`${where}: unmatched config-reference end marker before region`);
    const attributes = parseAttributes(match[1], where);
    for (const name of Object.keys(attributes))
      if (!["keys", "exclude", "level", "fallback", "title"].includes(name))
        throw new Error(`${where}: unknown attribute ${name}`);
    const list = (name: string) => {
      const value = attributes[name];
      if (value === true) throw new Error(`${where}: ${name} needs a value`);
      return value ? value.split(/[\s,]+/).filter(Boolean) : [];
    };
    const fallback = attributes.fallback === true;
    const keys = list("keys");
    if (attributes.fallback !== undefined && !fallback)
      throw new Error(`${where}: fallback takes no value`);
    if (fallback === Boolean(keys.length))
      throw new Error(`${where}: a region needs either keys or fallback`);
    const level = Number(attributes.level ?? 4);
    if (!Number.isInteger(level) || level < 2 || level > 6)
      throw new Error(`${where}: level must be an integer from 2 to 6`);
    if (attributes.title !== undefined && (!fallback || attributes.title === true))
      throw new Error(`${where}: title is only for the fallback region`);
    regions.push({
      file,
      start,
      end,
      keys,
      exclude: list("exclude"),
      level,
      fallback,
      title: typeof attributes.title === "string" ? attributes.title : undefined,
      context: headingContext(text.slice(0, match.index)),
    });
    cursor = end + endMarker.length;
  }
  if (text.slice(cursor).includes(endMarker))
    throw new Error(`${file}: unmatched config-reference end marker`);
  return regions;
}

const globCache = new Map<string, RegExp>();
export function matchesGlob(pattern: string, key: string): boolean {
  let regex = globCache.get(pattern);
  if (!regex) {
    const escape = (part: string) => part.replace(/[.+?^$()|[\]\\{}]/g, "\\$&");
    regex = new RegExp(`^${pattern.split("*").map(escape).join(".*")}$`);
    globCache.set(pattern, regex);
  }
  return regex.test(key);
}

// Assign every setting to exactly one region. An exact key name claims a setting over a glob; two
// regions claiming the same setting with equal specificity is an error. Settings no region claims
// go to the single fallback region.
export function assignSettings(settings: Setting[], regions: Region[]): Assignment {
  const warnings: string[] = [];
  const claims = new Map<string, { region: Region; exact: boolean; rank: number }[]>();
  const used = new Set<string>();
  for (const region of regions.filter(({ fallback }) => !fallback))
    for (const setting of settings) {
      if (region.exclude.some((pattern) => matchesGlob(pattern, setting.key))) continue;
      const rank = region.keys.findIndex((pattern) => matchesGlob(pattern, setting.key));
      if (rank < 0) continue;
      const exact = region.keys.includes(setting.key);
      used.add(`${region.file}\0${region.keys[rank]}`);
      if (exact) used.add(`${region.file}\0${setting.key}`);
      const list = claims.get(setting.key) ?? [];
      list.push({ region, exact, rank: exact ? region.keys.indexOf(setting.key) : rank });
      claims.set(setting.key, list);
    }
  const duplicates: string[] = [];
  const owner = new Map<string, { region: Region; rank: number }>();
  for (const [key, list] of claims) {
    const best = list.some(({ exact }) => exact) ? list.filter(({ exact }) => exact) : list;
    if (best.length > 1)
      duplicates.push(`${key}: ${best.map(({ region }) => region.file).join(", ")}`);
    else owner.set(key, best[0]);
  }
  if (duplicates.length)
    throw new Error(`config keys assigned to more than one region:\n${duplicates.join("\n")}`);
  for (const region of regions)
    for (const pattern of region.keys)
      if (!used.has(`${region.file}\0${pattern}`))
        warnings.push(`${region.file}: ${pattern} matches no config key`);
  const order = new Map(settings.map((setting, index) => [setting.key, index]));
  const result = regions
    .filter(({ fallback }) => !fallback)
    .map((region) => ({
      region,
      settings: settings
        .filter((setting) => owner.get(setting.key)?.region === region)
        .sort(
          (a, b) =>
            owner.get(a.key)!.rank - owner.get(b.key)!.rank ||
            order.get(a.key)! - order.get(b.key)!,
        ),
    }));
  const fallback = settings.filter((setting) => !owner.has(setting.key));
  const fallbacks = regions.filter((region) => region.fallback);
  if (fallbacks.length > 1)
    throw new Error(
      `expected one fallback region, found ${fallbacks.map(({ file }) => file).join(", ")}`,
    );
  if (fallback.length) {
    if (!fallbacks.length)
      throw new Error(
        `no fallback region for unassigned keys: ${fallback.map(({ key }) => key).join(", ")}`,
      );
    warnings.push(
      `keys in the fallback region (${fallbacks[0].file}); add them to a region: ${fallback.map(({ key }) => key).join(", ")}`,
    );
  }
  if (fallbacks.length) result.push({ region: fallbacks[0], settings: fallback });
  return { regions: result, fallback, warnings };
}

export function displayName(setting: Setting): string {
  const name =
    setting.section && setting.key.startsWith(`${setting.section}.`)
      ? setting.key.slice(setting.section.length + 1)
      : setting.key;
  return setting.table || setting.key === setting.section ? `[${name}]` : name;
}

const code = (text: string) => {
  const ticks = "`".repeat(
    Math.max(0, ...[...text.matchAll(/`+/g)].map(([run]) => run.length)) + 1,
  );
  return /^`|`$/.test(text) ? `${ticks} ${text} ${ticks}` : `${ticks}${text}${ticks}`;
};
const either = (items: string[]) =>
  items.length < 3
    ? items.join(" or ")
    : `${items.slice(0, -1).join(", ")}, or ${items[items.length - 1]}`;

// Make Rust doc-comment Markdown safe for MDX: escape JSX and expression syntax outside code,
// turn autolinks into links, drop rustdoc intra-doc link brackets and demote headings.
export function mdxSafe(markdown: string): string {
  let fence: string | undefined;
  return markdown
    .trim()
    .split("\n")
    .map((line) => {
      const marker = line.match(/^ {0,3}(`{3,}|~{3,})/);
      if (fence) {
        if (marker && marker[1][0] === fence[0] && marker[1].length >= fence.length)
          fence = undefined;
        return line;
      }
      if (marker) {
        fence = marker[1];
        return line;
      }
      return line
        .replace(/^ {0,3}#{1,6} +(.+?) *#*$/, "**$1**")
        .split(/(`+[^`]*`+)/)
        .map((part, index) =>
          index % 2
            ? part
            : part
                .replace(/<(https?:\/\/[^\s>]+)>/g, "[$1]($1)")
                .replace(/\[([A-Za-z_]\w*(?:::\w+)+)\](?![([:])/g, "`$1`")
                .replace(/\\?([{}<])/g, "\\$1"),
        )
        .join("")
        .replace(/\[(`[^`\]]+`)\](?![([:])/g, "$1");
    })
    .join("\n");
}

export function renderSetting(setting: Setting, level: number): string {
  const heading = `${"#".repeat(level)} ${code(displayName(setting))}`;
  const description = mdxSafe(setting.description);
  if (setting.table) return [heading, description].filter(Boolean).join("\n\n");
  const bullets = [
    `- Type: ${setting.type}`,
    `- Default: ${setting.default == null ? "none" : code(setting.default)}`,
  ];
  if (setting.env?.length) bullets.push(`- Environment: ${either(setting.env.map(code))}`);
  if (setting.values?.length) bullets.push(`- Values: ${setting.values.map(code).join(", ")}`);
  if (setting.aliases?.length) bullets.push(`- Aliases: ${setting.aliases.map(code).join(", ")}`);
  if (setting.deprecated) bullets.push(`- Deprecated: use ${code(setting.deprecated)} instead`);
  return [heading, bullets.join("\n"), description].filter(Boolean).join("\n\n");
}

export function renderRegion(region: Region, settings: Setting[]): string {
  // Children of a table key nest one level below it; a section's own table key does not nest
  // its keys, since the authored heading above the region already introduces the section.
  const tables = new Set(
    settings.filter(({ table, key, section }) => table && key !== section).map(({ key }) => key),
  );
  const blocks = settings.map((setting) => {
    const parts = setting.key.split(".");
    const depth = parts
      .slice(1)
      .filter((_, index) => tables.has(parts.slice(0, index + 1).join("."))).length;
    return renderSetting(setting, Math.min(6, region.level + depth));
  });
  if (region.title && blocks.length)
    blocks.unshift(`${"#".repeat(region.level - 1)} ${region.title}`);
  return blocks.length ? `\n\n${blocks.join("\n\n")}\n\n` : "\n";
}

const summary = (setting: Setting) =>
  (setting.description.trim().split(/\n\s*\n/)[0] ?? "")
    .replace(/\s*\n\s*/g, " ")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/\[(`[^`\]]+`)\](?![([:])/g, "$1")
    .trim();

export function renderDefaultConfig(assignment: Assignment): string {
  const entries = assignment.regions.flatMap(({ region, settings }) =>
    settings
      .filter((setting) => setting.default != null && !setting.deprecated)
      .map((setting) => ({ setting, context: region.context })),
  );
  const blocks: string[] = [];
  const emit = (header: string, list: typeof entries) => {
    let context: string | undefined;
    const lines = [header];
    for (const { setting, context: next } of list) {
      if (next !== context) {
        const rule = `# ${"=".repeat(77)}`;
        lines.push("", rule, `# ${next.toUpperCase()}`, rule);
        context = next;
      }
      const name = setting.section ? setting.key.slice(setting.section.length + 1) : setting.key;
      const about = summary(setting);
      lines.push("", ...(about ? [`# ${about}`] : []), `# Default: ${setting.default}`);
      lines.push(`${name} = ${setting.default}`);
    }
    blocks.push(lines.join("\n"));
  };
  emit(
    "[profile.default]",
    entries.filter(({ setting }) => !setting.section),
  );
  const sections = [...new Set(entries.flatMap(({ setting }) => setting.section ?? []))];
  for (const section of sections)
    emit(
      `[${section}]`,
      entries.filter(({ setting }) => setting.section === section),
    );
  return `${generatedNotice}

## Default foundry configuration

The configuration Foundry uses when \`foundry.toml\` sets nothing. Keys of a section, such as
\`[fuzz]\`, can also be written under \`[profile.<name>.<section>]\`. Keys without a default are omitted;
see the [reference](/config/reference/overview) for every key.

\`\`\`toml
${blocks.join("\n\n")}
\`\`\`
`;
}

function pages(root: string): string[] {
  const files = readdirSync(join(root, pagesPath))
    .filter((file) => file.endsWith(".mdx") && `${pagesPath}/${file}` !== defaultConfigPath)
    .map((file) => file.slice(0, -4));
  const rank = (page: string) =>
    pageOrder.includes(page) ? pageOrder.indexOf(page) : pageOrder.length;
  return files
    .sort((a, b) => rank(a) - rank(b) || a.localeCompare(b, "en"))
    .map((page) => `${pagesPath}/${page}.mdx`);
}

// Render every generated region and default-config.mdx from settings without writing anything.
export function render(
  root: string,
  settings: Setting[],
): { files: Map<string, string>; assignment: Assignment } {
  const texts = new Map(pages(root).map((path) => [path, read(root, path)]));
  const regions = [...texts].flatMap(([path, text]) => parseRegions(text, path));
  const assignment = assignSettings(settings, regions);
  const files = new Map<string, string>();
  for (const [path, text] of texts) {
    const own = assignment.regions.filter(({ region }) => region.file === path);
    if (!own.length) continue;
    let output = "";
    let cursor = 0;
    for (const { region, settings } of own.sort((a, b) => a.region.start - b.region.start)) {
      output += text.slice(cursor, region.start) + renderRegion(region, settings);
      cursor = region.end;
    }
    files.set(path, output + text.slice(cursor));
  }
  files.set(defaultConfigPath, renderDefaultConfig(assignment));
  return { files, assignment };
}

const serialize = (snapshot: Snapshot) => `${JSON.stringify(snapshot, null, 2)}\n`;

export function readSnapshot(root: string): Snapshot {
  const snapshot = JSON.parse(read(root, snapshotPath)) as Snapshot;
  if (
    snapshot.source?.repository !== "foundry-rs/foundry" ||
    snapshot.source.path !== sourcePath ||
    !/^[a-f0-9]{40}$/.test(snapshot.source.commit)
  )
    throw new Error(`${snapshotPath}: invalid source`);
  validateSettings(snapshot, snapshotPath);
  return snapshot;
}

export function readFoundry(
  foundry: string,
  commit?: string,
): { snapshot: Snapshot; warnings: string[] } {
  const warnings: string[] = [];
  const settings = validateSettings(
    JSON.parse(read(foundry, sourcePath)),
    join(foundry, sourcePath),
  );
  if (!commit) {
    try {
      commit = git(foundry, "rev-parse", "HEAD");
    } catch {
      throw new Error("cannot read the Foundry commit with git; pass --commit <sha>");
    }
    let dirty = "";
    try {
      dirty = git(foundry, "status", "--porcelain", "--", sourcePath);
    } catch {}
    if (dirty)
      warnings.push(
        `${sourcePath} has uncommitted changes; the snapshot records ${commit} but may not match it`,
      );
  }
  if (!/^[a-f0-9]{40}$/.test(commit))
    throw new Error("expected a full 40-character Foundry commit SHA");
  return {
    snapshot: {
      schemaVersion: 1,
      source: { repository: "foundry-rs/foundry", commit, path: sourcePath },
      settings,
    },
    warnings,
  };
}

const changedFiles = (root: string, files: Map<string, string>) =>
  [...files].filter(([path, text]) => {
    try {
      return read(root, path) !== text;
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") return true;
      throw error;
    }
  });

export type Options = { foundry?: string; commit?: string; check?: boolean };
export type Result = { changed: string[]; warnings: string[]; fallback: string[] };

// Import (or with check, verify) the config reference. Throws when the book is stale or invalid.
export function run(root: string, options: Options): Result {
  if (!options.foundry && !options.check)
    throw new Error("--foundry <checkout> is required when importing");
  if (options.commit && !options.foundry) throw new Error("--commit needs --foundry");
  const warnings: string[] = [];
  let snapshot: Snapshot;
  if (options.foundry) {
    const source = readFoundry(resolve(options.foundry), options.commit);
    warnings.push(...source.warnings);
    snapshot = source.snapshot;
  } else snapshot = readSnapshot(root);
  const { files, assignment } = render(root, snapshot.settings);
  warnings.push(...assignment.warnings);
  files.set(snapshotPath, serialize(snapshot));
  const changed = changedFiles(root, files);
  const result = {
    changed: changed.map(([path]) => path),
    warnings,
    fallback: assignment.fallback.map(({ key }) => key),
  };
  if (options.check) {
    if (changed.length)
      throw Object.assign(
        new Error(
          `generated config reference is stale; run import:config -- --foundry <checkout>:\n${result.changed.join("\n")}`,
        ),
        { warnings },
      );
  } else for (const [path, text] of changed) writeFileSync(join(root, path), text);
  return result;
}

export function main(
  args = process.argv.slice(2),
  root = resolve(import.meta.dirname, ".."),
): void {
  const { values } = parseArgs({
    args: args.filter((arg) => arg !== "--"),
    options: {
      foundry: { type: "string" },
      commit: { type: "string" },
      check: { type: "boolean" },
      help: { type: "boolean" },
    },
  });
  if (values.help) {
    console.log(
      "Usage: vp run import:config -- --foundry <checkout> [--commit <sha>] [--check]\n       vp run import:config -- --check\n\nImport Foundry's crates/config/assets/config-reference.json into the generated regions of\nsrc/pages/config/reference/ and default-config.mdx. --check never writes files; without\n--foundry it re-renders the committed scripts/config-reference.json snapshot offline.",
    );
    return;
  }
  let result: Result;
  try {
    result = run(root, values);
  } catch (error) {
    for (const warning of (error as { warnings?: string[] }).warnings ?? [])
      console.warn(`warning: ${warning}`);
    throw error;
  }
  for (const warning of result.warnings) console.warn(`warning: ${warning}`);
  console.log(
    `${values.check ? "Checked" : "Imported"} config reference; ${result.changed.length} changed files.`,
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main();
